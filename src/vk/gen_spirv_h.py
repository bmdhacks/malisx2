# Writes a SPIR-V module as a C array of words (--name) for the driver to
# compile at run time (vk/cl/mali_tess.cl).

import argparse
import struct

ap = argparse.ArgumentParser()
ap.add_argument('--name', required=True)
ap.add_argument('input')
ap.add_argument('output')
args = ap.parse_args()

data = open(args.input, 'rb').read()
words = struct.unpack('<%dI' % (len(data) // 4), data)
with open(args.output, 'w') as f:
    f.write('/* Generated by gen_spirv_h.py. */\n#include <stdint.h>\n')
    f.write('static const uint32_t %s[] = {\n' % args.name)
    for i in range(0, len(words), 8):
        f.write('   ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',\n')
    f.write('};\n')
